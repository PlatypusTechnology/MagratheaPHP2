<h1>MagratheaPHP 3.0 is out</h1>

<p>You're reading the docs for <strong>MagratheaPHP2</strong>. The next major version,
<strong>MagratheaPHP 3.0</strong>, is ready, and it's built to be worked on by AI coding
assistants and agents as well as by people.</p>

<h2>Built for AI assistants and agents</h2>
<ul>
	<li><strong><code>skill.md</code></strong>: a coding cookbook for AI assistants that covers the
	framework's conventions, patterns, and the mistakes to avoid. Hand it to your assistant before
	it writes a line of code for your project.</li>
	<li><strong><code>AGENTS.md</code></strong>: instructions for coding agents working inside a
	MagratheaPHP project.</li>
	<li><strong>Reflection-generated reference</strong>: method and class signatures in the 3.0 docs
	are read live from the source on every page load. An agent that reads them gets the real,
	current API, not one that has drifted from the code.</li>
</ul>

